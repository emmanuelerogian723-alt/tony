def A(slug, name, desc, method, url, params=None, required=None, tier="read", resp=None, headers=None, note=""):
    a = {"slug": slug, "name": name, "description": desc, "method": method, "url": url}
    if params:
        a["params"] = params
    if required:
        a["required"] = required
    if tier != "read":
        a["tier"] = tier
    if resp:
        a["response"] = resp
    if headers:
        a["headers"] = headers
    if note:
        a["danger_note"] = note
    return a


def P(**kw):
    return kw


def s(desc="", **kw):
    return {"type": "string", "description": desc, **kw}


def i(desc="", **kw):
    return {"type": "integer", "description": desc, **kw}


def b(desc="", **kw):
    return {"type": "boolean", "description": desc, **kw}


