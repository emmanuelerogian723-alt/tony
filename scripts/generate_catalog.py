AUTH_DEFAULT = {"type": "none"}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for app in APPS:
        doc = {
            "slug": app["slug"],
            "name": app["name"],
            "category": app["category"],
            "description": app["description"],
            "docs": app.get("docs", ""),
            "logo": f"https://cdn.simpleicons.org/{app['logo']}",
            "verified": bool(app.get("verified", True)),
            "auth": app.get("auth", AUTH_DEFAULT),
        }
        if app.get("base"):
            doc["base_url"] = app["base"]
        if app.get("default_headers"):
            doc["default_headers"] = app["default_headers"]
        doc["actions"] = app["actions"]
        if app.get("notes"):
            doc["notes"] = app["notes"]
        path = OUT / f"{app['slug']}.yaml"
        with path.open("w") as fh:
            yaml.safe_dump(doc, fh, sort_keys=False, allow_unicode=True, width=120)
        written += 1
    print(f"wrote {written} manifests to {OUT}")


if __name__ == "__main__":
    main()
